// Every suffix these tests create is under example.com (RFC 2606), so a run can never claim a domain
// someone owns. The id is never asserted to equal the suffix: on tenants with the suffixless
// configuration it is <tenant-id>.<suffix>, and these tests must pass on both kinds.

func randomTestSuffix(prefix string) string {
	return framework.RandomResourceName(prefix) + ".example.com"
}

// createTestSuffix creates a suffix and registers its cleanup. The cleanup tolerates ErrNotFound,
// because a test may already have renamed or deleted the suffix by the time it runs.
func createTestSuffix(ctx *framework.TestContext, svc *tenantsuffixes.IdsecIdentityTenantSuffixesService, suffix string) *tenantsuffixesmodels.IdsecIdentityTenantSuffix {
	ctx.T.Helper()
	ctx.T.Logf("Creating suffix: %s", suffix)
	created, err := svc.Create(&tenantsuffixesmodels.IdsecIdentityCreateTenantSuffix{ReplaceDomain: suffix})
	trackTestSuffix(ctx, svc, suffix)
	require.NoError(ctx.T, err, "Create tenant suffix failed")
	require.NotNil(ctx.T, created)
	require.NotEmpty(ctx.T, created.ID, "created suffix should have an id")
	return created
}

func trackTestSuffix(ctx *framework.TestContext, svc *tenantsuffixes.IdsecIdentityTenantSuffixesService, suffix string) {
	ctx.TrackResourceByType("IdentityTenantSuffix", suffix, func() error {
		err := svc.Delete(&tenantsuffixesmodels.IdsecIdentityDeleteTenantSuffix{ReplaceDomain: suffix})
		if errors.Is(err, common.ErrNotFound) {
			return nil
		}
		return err
	})
}

// Generated by gene2e on 2026-09-30 06:25:28
// Service: pkg/services/identity/tenantsuffixes
