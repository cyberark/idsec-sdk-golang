// TestIdentityTenantSuffixes creates a suffix, reads it back every way the service offers, renames
// it, then deletes it.
func TestIdentityTenantSuffixes(t *testing.T) {
	framework.Run(t, func(ctx *framework.TestContext) {
		framework.LogSection(t, "Test: Identity Tenant Suffixes")

		svc, err := ctx.API.IdentityTenantsuffixes()
		require.NoError(t, err)

		original := randomTestSuffix("e2e-sfx")
		renamed := randomTestSuffix("e2e-sfx-renamed")

		created := createTestSuffix(ctx, svc, original)
		assert.Equal(t, original, created.ReplaceDomain)

		t.Log("Get by suffix...")
		bySuffix, err := svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ReplaceDomain: original})
		require.NoError(t, err, "Get by suffix failed")
		assert.Equal(t, created.ID, bySuffix.ID)
		assert.Equal(t, original, bySuffix.ReplaceDomain)

		t.Log("Get by id...")
		byID, err := svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ID: created.ID})
		require.NoError(t, err, "Get by id failed")
		assert.Equal(t, created.ID, byID.ID)
		assert.Equal(t, original, byID.ReplaceDomain)

		t.Log("Get by suffix in a different case...")
		byUpper, err := svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ReplaceDomain: strings.ToUpper(original)})
		require.NoError(t, err, "Get should match the suffix case-insensitively")
		assert.Equal(t, created.ID, byUpper.ID)

		t.Log("List and ListBy...")
		all, err := svc.List()
		require.NoError(t, err, "List failed")
		found := false
		for _, s := range all {
			require.NotNil(t, s)
			assert.NotEmpty(t, s.ReplaceDomain, "every listed suffix should have a suffix")
			if s.ID == created.ID && s.ReplaceDomain == original {
				found = true
			}
		}
		assert.True(t, found, "List should include the suffix created in this test")
		filtered, err := svc.ListBy(&tenantsuffixesmodels.IdsecIdentityTenantSuffixFilters{ReplaceDomain: original})
		require.NoError(t, err, "ListBy failed")
		require.Len(t, filtered, 1, "ListBy should return exactly the suffix created in this test")
		assert.Equal(t, created.ID, filtered[0].ID)

		t.Logf("Renaming suffix: %s -> %s", original, renamed)
		updated, err := svc.Update(&tenantsuffixesmodels.IdsecIdentityUpdateTenantSuffix{ID: created.ID, ReplaceDomain: renamed})
		// Tracked before the error check: a rename that fails part-way can leave the new suffix behind.
		trackTestSuffix(ctx, svc, renamed)
		require.NoError(t, err, "Rename tenant suffix failed")
		require.NotNil(t, updated)
		assert.Equal(t, renamed, updated.ReplaceDomain)
		assert.NotEqual(t, created.ID, updated.ID, "a rename should change the server's key")

		afterRename, err := svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ID: updated.ID})
		require.NoError(t, err, "Get of the renamed suffix failed")
		assert.Equal(t, renamed, afterRename.ReplaceDomain)

		_, err = svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ReplaceDomain: original})
		require.ErrorIs(t, err, common.ErrNotFound, "the old suffix should be gone after a rename")

		t.Log("Delete suffix...")
		err = svc.Delete(&tenantsuffixesmodels.IdsecIdentityDeleteTenantSuffix{ReplaceDomain: renamed})
		require.NoError(t, err, "Delete tenant suffix failed")

		_, err = svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ReplaceDomain: renamed})
		require.ErrorIs(t, err, common.ErrNotFound, "provider Read handlers depend on the common.ErrNotFound chain")

		err = svc.Delete(&tenantsuffixesmodels.IdsecIdentityDeleteTenantSuffix{ReplaceDomain: renamed})
		require.ErrorIs(t, err, common.ErrNotFound, "deleting a deleted suffix should report not found")

		t.Log("Lifecycle completed successfully")
	}, tenantsuffixes.ServiceConfig)
}

// TestIdentityTenantSuffixesKeepsSpellingAndRejectsDuplicates checks the server stores a mixed-case
// suffix exactly as written -- the provider relies on that to read back what was planned -- and that
// the same suffix in another case is the same suffix, not a second one.
func TestIdentityTenantSuffixesKeepsSpellingAndRejectsDuplicates(t *testing.T) {
	framework.Run(t, func(ctx *framework.TestContext) {
		framework.LogSection(t, "Test: Identity Tenant Suffixes Spelling and Duplicates")

		svc, err := ctx.API.IdentityTenantsuffixes()
		require.NoError(t, err)

		mixed := "E2E-Case-" + strings.TrimPrefix(framework.RandomResourceName("x"), "x-") + ".Example.com"
		created := createTestSuffix(ctx, svc, mixed)
		assert.Equal(t, mixed, created.ReplaceDomain, "the server should store the suffix as written")

		byLower, err := svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ReplaceDomain: strings.ToLower(mixed)})
		require.NoError(t, err, "Get by the lower-case spelling failed")
		assert.Equal(t, created.ID, byLower.ID)
		assert.Equal(t, mixed, byLower.ReplaceDomain, "a read should return the stored spelling")

		t.Log("Creating the same suffix in lower case...")
		_, err = svc.Create(&tenantsuffixesmodels.IdsecIdentityCreateTenantSuffix{ReplaceDomain: strings.ToLower(mixed)})
		require.Error(t, err, "a suffix that differs only in case should be rejected as a duplicate")

		filtered, err := svc.ListBy(&tenantsuffixesmodels.IdsecIdentityTenantSuffixFilters{ReplaceDomain: mixed})
		require.NoError(t, err, "ListBy failed")
		require.Len(t, filtered, 1, "the rejected duplicate should not have added a second suffix")
		assert.Equal(t, mixed, filtered[0].ReplaceDomain)
	}, tenantsuffixes.ServiceConfig)
}

// TestIdentityTenantSuffixesRejectsInvalidSuffix checks the server refuses a suffix outside its
// naming rule, the same one the provider's plan-time validator mirrors. If the server ever accepted
// it, the provider would be stricter than the portal.
func TestIdentityTenantSuffixesRejectsInvalidSuffix(t *testing.T) {
	framework.Run(t, func(ctx *framework.TestContext) {
		framework.LogSection(t, "Test: Identity Tenant Suffixes Invalid Suffix")

		svc, err := ctx.API.IdentityTenantsuffixes()
		require.NoError(t, err)

		invalid := framework.RandomResourceName("e2e-bad") + "/x.example.com"
		// Tracked in case the server accepts it, so a failing run still leaves the tenant clean.
		trackTestSuffix(ctx, svc, invalid)

		t.Logf("Creating invalid suffix: %s", invalid)
		_, err = svc.Create(&tenantsuffixesmodels.IdsecIdentityCreateTenantSuffix{ReplaceDomain: invalid})
		require.Error(t, err, "the server should reject a suffix containing '/'")

		_, err = svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ReplaceDomain: invalid})
		require.ErrorIs(t, err, common.ErrNotFound, "a rejected suffix should not have been stored")
	}, tenantsuffixes.ServiceConfig)
}

// TestIdentityTenantSuffixesRenameOntoExistingFails checks a rename onto a suffix the tenant already
// has is refused by the server and leaves both suffixes as they were.
func TestIdentityTenantSuffixesRenameOntoExistingFails(t *testing.T) {
	framework.Run(t, func(ctx *framework.TestContext) {
		framework.LogSection(t, "Test: Identity Tenant Suffixes Rename Onto Existing")

		svc, err := ctx.API.IdentityTenantsuffixes()
		require.NoError(t, err)

		first := createTestSuffix(ctx, svc, randomTestSuffix("e2e-sfx-a"))
		second := createTestSuffix(ctx, svc, randomTestSuffix("e2e-sfx-b"))

		t.Logf("Renaming %s onto %s...", first.ReplaceDomain, second.ReplaceDomain)
		_, err = svc.Update(&tenantsuffixesmodels.IdsecIdentityUpdateTenantSuffix{ID: first.ID, ReplaceDomain: second.ReplaceDomain})
		require.Error(t, err, "renaming onto an existing suffix should fail")

		stillFirst, err := svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ID: first.ID})
		require.NoError(t, err, "the suffix being renamed should still exist")
		assert.Equal(t, first.ReplaceDomain, stillFirst.ReplaceDomain)

		stillSecond, err := svc.Get(&tenantsuffixesmodels.IdsecIdentityGetTenantSuffix{ID: second.ID})
		require.NoError(t, err, "the rename target should still exist")
		assert.Equal(t, second.ReplaceDomain, stillSecond.ReplaceDomain)
	}, tenantsuffixes.ServiceConfig)
}
